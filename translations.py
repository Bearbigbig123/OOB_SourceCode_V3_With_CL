"""
多語言翻譯管理系統
支援繁體中文 (ZH_TW)、英文 (EN)、韓文 (KO) 與日文 (JA)
"""

class TranslationManager:
    """全域翻譯管理器 - 單例模式"""
    _instance = None
    _current_lang = "ZH_TW"  # 預設繁體中文
    SUPPORTED_LANGS = ("ZH_TW", "EN", "KO", "JA")
    
    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance
    
    def __init__(self):
        if not hasattr(self, '_initialized'):
            self._initialized = True
            self._observers = []  # 觀察者列表
    
    @property
    def current_lang(self):
        return self._current_lang
    
    @current_lang.setter
    def current_lang(self, lang):
        if lang not in self.SUPPORTED_LANGS:
            raise ValueError(f"Unsupported language: {lang}")
        if self._current_lang != lang:
            self._current_lang = lang
            self._notify_observers()
    
    def register_observer(self, observer):
        """註冊觀察者（需要更新UI的 Widget）"""
        if observer not in self._observers:
            self._observers.append(observer)
    
    def unregister_observer(self, observer):
        """取消註冊觀察者"""
        if observer in self._observers:
            self._observers.remove(observer)
    
    def _notify_observers(self):
        """通知所有觀察者語言已改變"""
        for observer in self._observers:
            if hasattr(observer, 'refresh_ui_texts'):
                try:
                    observer.refresh_ui_texts()
                except Exception as e:
                    print(f"Error refreshing UI for {observer}: {e}")
    
    def get(self, key, default=""):
        """獲取翻譯文字"""
        translations = getattr(Translations, self._current_lang, Translations.EN)
        return translations.get(key, Translations.EN.get(key, default))

    def is_translation_value(self, key, value):
        """Return whether value is a translation of key in any supported language."""
        return any(
            getattr(Translations, lang, {}).get(key) == value
            for lang in self.SUPPORTED_LANGS
        )
    
    def toggle_language(self):
        """依序切換繁中、英文、韓文與日文。"""
        current_index = self.SUPPORTED_LANGS.index(self._current_lang)
        self.current_lang = self.SUPPORTED_LANGS[
            (current_index + 1) % len(self.SUPPORTED_LANGS)
        ]
        return self.current_lang


